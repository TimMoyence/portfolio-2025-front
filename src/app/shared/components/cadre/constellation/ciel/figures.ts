export type Etoile = readonly [ascensionDroite: number, declinaison: number, magnitude: number];

export interface Figure {
  readonly nom: string;
  readonly etoiles: readonly Etoile[];
  readonly segments: readonly (readonly [number, number])[];
}

const figure = (
  nom: string,
  etoiles: readonly Etoile[],
  traces: readonly (readonly number[])[],
): Figure => ({
  nom,
  etoiles,
  segments: traces.flatMap((trace) =>
    trace.slice(1).map((arrivee, index): [number, number] => [trace[index], arrivee]),
  ),
});

